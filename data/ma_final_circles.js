function numeric(q, a, exp, maDiagram){
  return {type:'suji',lv:'標準',q,a:[String(a)],exp,examPractice:true,...(maDiagram?{maDiagram}:{})};
}
function choice(q, choices, a, exp, maDiagram){
  return {type:'yon',lv:'標準',q,choices,a,exp,examPractice:true,...(maDiagram?{maDiagram}:{})};
}
function truth(q, a, exp, maDiagram){
  return {type:'maru',lv:'基礎',q,a,exp,examPractice:true,...(maDiagram?{maDiagram}:{})};
}
function triangle(labels){
  return {kind:'geometry',points:{A:[245,35],B:[75,250],C:[425,250]},segments:[['A','B'],['B','C'],['C','A']],labels};
}
function circle(labels, extra=[]){
  return {kind:'geometry',points:{A:[175,50],B:[175,250],C:[350,225],D:[350,75]},
    segments:[['A','B'],['B','C'],['C','D'],['D','A'],...extra],circles:[{cx:250,cy:150,r:125}],labels};
}
function diameter(labels, extra=[]){
  return {kind:'geometry',points:{A:[125,150],B:[285,30],C:[375,150],D:[285,270]},
    segments:[['A','B'],['B','C'],['C','A'],['A','D'],['D','C'],...extra],circles:[{cx:250,cy:150,r:125}],labels};
}
function central(labels){
  return {kind:'geometry',points:{A:[150,225],B:[350,225],P:[250,25],O:[250,150]},
    segments:[['A','O'],['O','B'],['A','P'],['P','B']],circles:[{cx:250,cy:150,r:125}],labels,pointOffsets:{O:[0,22]}};
}

