function choice(q, answer, wrong, exp) {
  return {type:'yon',lv:'標準',q,choices:[answer,...wrong],a:0,exp,examPractice:true};
}
function input(q, answer, exp, accept=[]) {
  return {type:'ana',lv:'基礎',q,choices:[answer],a:0,accept,forceInput:true,exp,examPractice:true};
}
