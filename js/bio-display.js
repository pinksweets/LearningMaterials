      drawing=box(105,15,390,65,['① 血小板が傷口に集まる'],'#fff2cf')+arrow(300,80,300,110)+box(105,110,390,65,['② フィブリンの網ができる'])+arrow(300,175,300,205)+box(105,205,390,65,['③ 血球が絡み、血ぺいに'],'#ffe3e7')+arrow(300,270,300,300)+box(75,300,450,75,['傷口をふさぎ、出血を止める'])+text(300,415,'凝固後の上澄み＝血清',22);
