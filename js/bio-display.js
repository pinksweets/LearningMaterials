      desc=quiz?'Aは血管内、Bは細胞の周り、Cはリンパ管内の体液。AとBの間で物質を交換し、Bの一部はCとなってAへ戻る。':'血しょうの一部が組織液となり、細胞と酸素・栄養分・老廃物を交換する。組織液の大部分は毛細血管へ、一部はリンパ管を経て血液へ戻る。';
