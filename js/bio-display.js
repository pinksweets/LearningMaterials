/* 教科書写真をもとにしたオリジナル模式図。外部画像・フォント不要。 */
import { escapeHtml } from './utils.js';

function text(x,y,value,size=22){return `<text x="${x}" y="${y}" text-anchor="middle" font-size="${size}">${escapeHtml(value)}</text>`;}
function box(x,y,w,h,lines,color='#e4f5ee'){
  return `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="16" fill="${color}" stroke="#55756b" stroke-width="2"/>`+lines.map((s,i)=>text(x+w/2,y+h/2+(i-(lines.length-1)/2)*28+8,s)).join('');
}
function arrow(x1,y1,x2,y2,color='#356a94'){
  const a=Math.atan2(y2-y1,x2-x1),s=12;
  return `<path d="M${x1} ${y1} L${x2} ${y2}" fill="none" stroke="${color}" stroke-width="4"/><path d="M${x2-s*Math.cos(a-.5)} ${y2-s*Math.sin(a-.5)} L${x2} ${y2} L${x2-s*Math.cos(a+.5)} ${y2-s*Math.sin(a+.5)}" fill="none" stroke="${color}" stroke-width="4"/>`;
}

